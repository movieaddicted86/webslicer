/**
 * Export use cases: read an uploaded 3MF project and build the two downloads (a PrusaSlicer 3MF
 * project and the config INI). The routes only answer.
 */
import { activeSchema } from './schema.js';
import { build3mfForRequest, validateSliceRequest } from './slice.js';
import { mergeConfigs } from './configMerge.js';
import { read3mfProject } from '../slicer/threemf/index.js';
import { serializeIni } from '../slicer/ini.js';
import { ValidationError } from '../errors.js';
import type { IniSection } from '../slicer/ini.js';
import type { CustomGcode, ProjectObject, SliceRequest } from '@webslicer/shared';

/** What a parsed 3MF project upload carries. */
export interface ImportedProject {
  config: IniSection;
  objects: ProjectObject[];
  customGcodes: CustomGcode[];
  buildOrder: number[];
}

/** Parse an uploaded 3MF; an empty or unreadable body is a 400 with the message the route showed. */
export async function readProjectUpload(body: unknown): Promise<ImportedProject> {
  if (!Buffer.isBuffer(body) || !body.length) throw new ValidationError('empty body');
  try {
    return await read3mfProject(body);
  } catch (e) {
    throw new ValidationError(`cannot read 3MF: ${(e as Error).message}`);
  }
}

/** Refuse an invalid export body as the client error it is (400), not as an internal error. */
function validRequest(raw: unknown): SliceRequest {
  try {
    return validateSliceRequest(raw);
  } catch (e) {
    throw new ValidationError((e as Error).message);
  }
}

/** The 3MF project download of a request: the bytes and the file name. */
export async function project3mfExport(raw: unknown): Promise<{ buf: Buffer; name: string }> {
  const body = validRequest(raw);
  const schema = await activeSchema();
  const merged = mergeConfigs(schema, body, { forProject: true });
  const buf = await build3mfForRequest(body, merged);
  const name = (body.outputName || 'project').replace(/[^A-Za-z0-9._ -]/g, '_') + '.3mf';
  return { buf, name };
}

/** The PrusaSlicer config INI of a request. */
export async function configExport(raw: unknown): Promise<string> {
  const body = validRequest(raw);
  const schema = await activeSchema();
  const merged = mergeConfigs(schema, { ...body, objects: body.objects || [] });
  return serializeIni(merged, 'generated by WebSlicer');
}
