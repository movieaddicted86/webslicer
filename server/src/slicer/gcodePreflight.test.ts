/**
 * The file side of the preflight: async reading, binary output, a missing file. The rules themselves
 * are pinned in `shared/src/safety/gcodePreflight.test.ts`; this file checks the server wrapper.
 */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { test } from 'node:test';
import { isBinaryGcode, machineLimitsOf, scanGcodeFile } from './gcodePreflight.js';
import { PREFLIGHT_VERSION } from '@webslicer/shared';

const DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'ws-preflight-'));

test.after(() => fs.rmSync(DIR, { recursive: true, force: true }));

/** A file of about `mb` megabytes of realistic-looking G-code. */
function bigFile(name: string, mb = 20): { file: string; size: number } {
  const line = 'G1 X12.345 Y67.890 E0.01234\n';
  const file = path.join(DIR, name);
  const text = line.repeat(Math.ceil((mb * 1024 * 1024) / line.length));
  fs.writeFileSync(file, text);
  return { file, size: fs.statSync(file).size };
}

test('a clean file scans to no issues; a forbidden command is found with its line', async () => {
  const file = path.join(DIR, 'clean.gcode');
  fs.writeFileSync(file, '; generated by PrusaSlicer\nG28\nG1 X10 Y10\n');
  assert.deepEqual(await scanGcodeFile(file), {
    version: PREFLIGHT_VERSION,
    issues: [],
    counts: {},
    maxTemperatures: { hotend: 0, bed: 0 },
  });

  fs.writeFileSync(file, 'G28\nG1 X10 Y10\nM500\n');
  const result = await scanGcodeFile(file);
  assert.equal(result.issues.length, 1);
  assert.equal(result.issues[0].rule, 'gcode.forbidden_command');
  assert.equal(result.issues[0].line, 3);
  assert.equal(result.issues[0].text, 'M500');
});

test('the machine limits of the preset reach the firmware-limit rule', async () => {
  const file = path.join(DIR, 'limits.gcode');
  fs.writeFileSync(file, 'G28\nM203 X250\n');
  assert.deepEqual((await scanGcodeFile(file)).counts, {}, 'no limits given: nothing to compare');
  const result = await scanGcodeFile(file, machineLimitsOf({ machine_max_feedrate_x: '200,100', other: '1' }));
  assert.deepEqual(result.counts, { 'gcode.firmware_limit': 1 });
});

test('binary G-code and a missing file are one warning, not an error', async () => {
  const binary = await scanGcodeFile(path.join(DIR, 'part.bgcode'));
  assert.equal(binary.version, PREFLIGHT_VERSION);
  assert.deepEqual(binary.counts, { 'gcode.not_scanned': 1 });
  assert.deepEqual(
    binary.issues.map((i) => [i.rule, i.severity, i.line]),
    [['gcode.not_scanned', 'warn', 0]],
  );
  const missing = await scanGcodeFile(path.join(DIR, 'gone.gcode'));
  assert.deepEqual(missing.counts, { 'gcode.not_scanned': 1 });
  assert.ok(isBinaryGcode('PART.BGCODE'));
  assert.equal(isBinaryGcode('part.gcode'), false);
});

/**
 * The scan is awaited between 256 KiB chunks, so the event loop keeps running while a large file is
 * read. A synchronous read of the 20 MB file left the timer with zero ticks; the async one has to fire
 * many times, and no single stall may come near the whole scan time.
 */
test('a large file does not block the event loop while it is scanned', async () => {
  const { file, size } = bigFile('big.gcode');
  let ticks = 0;
  const timer = setInterval(() => ticks++, 2);
  const started = performance.now();
  const result = await scanGcodeFile(file);
  const ms = performance.now() - started;
  clearInterval(timer);
  assert.deepEqual(result.counts, { 'gcode.no_homing': 1 }, 'the first move has no G28 before it');

  assert.ok(size > 15 * 1024 * 1024, `the fixture is ${size} bytes`);
  // Many ticks mean the scan kept yielding; a blocking read leaves single digits. The threshold is
  // generous because the suite runs many files in parallel and timer callbacks then arrive late – the
  // distinction under test is "yields at all" vs "blocks for 20 MB", not the tick rate.
  assert.ok(ticks >= 10 && ticks >= ms / 40, `${ticks} timer ticks in ${ms.toFixed(0)} ms`);
});

test('a multi-byte character on a chunk boundary is decoded correctly', async () => {
  // "°" is two bytes in UTF-8. Line 2 starts so that its first ° byte is the last byte of the first
  // 256 KiB chunk – a naive `toString` per chunk would cut the character into two replacement chars.
  const degreeAt = 256 * 1024 - 1;
  const prefix = 'M500 ; '; // 7 bytes, then the ° – so line 2 has to start at degreeAt - 7
  const padding = `;${'x'.repeat(degreeAt - prefix.length - 2)}\n`;
  const file = path.join(DIR, 'utf8.gcode');
  fs.writeFileSync(file, `${padding}${prefix}°C\nG28\n`);
  assert.equal(Buffer.byteLength(padding) + prefix.length, degreeAt, 'the ° starts on the chunk boundary');

  const result = await scanGcodeFile(file);
  assert.deepEqual(
    result.issues.map((i) => i.text),
    ['M500 ; °C'],
  );
  assert.equal(result.issues[0].text.includes('�'), false, 'no replacement character');
});
