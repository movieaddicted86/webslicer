/**
 * The `thumbnails` option parser itself is tested in `shared/src/values.test.ts` (R-5 moved it
 * there); this file covers what only the server does with a thumbnail – the G-code block and the
 * rewrite of the file.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { injectThumbnails, thumbnailBlock } from './thumbnails.js';

test('thumbnail block format', () => {
  const b64 = 'A'.repeat(100);
  const block = thumbnailBlock({ width: 16, height: 16, format: 'QOI', data: b64 });
  const lines = block.trimEnd().split('\n');
  assert.equal(lines[0], ';');
  assert.equal(lines[1], '; thumbnail_QOI begin 16x16 100');
  assert.equal(lines[2].length, 80); // "; " + 78 chars
  assert.equal(lines[3], '; ' + 'A'.repeat(22));
  assert.equal(lines[4], '; thumbnail_QOI end');
  assert.equal(lines[5], ';');
});

test('injectThumbnails rewrites the file after the first line', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ws-thumb-'));
  const f = path.join(dir, 't.gcode');
  fs.writeFileSync(f, '; generated by PrusaSlicer\n\n; external perimeters extrusion width = 0.45mm\nG28\nG1 X10\n');
  await injectThumbnails(f, [{ width: 16, height: 16, format: 'PNG', data: 'iVBORw0KGgo=' }]);
  const text = fs.readFileSync(f, 'utf8');
  const lines = text.split('\n');
  assert.equal(lines[0], '; generated by PrusaSlicer');
  assert.equal(lines[1], '');
  assert.equal(lines[2], ';');
  assert.equal(lines[3], '; thumbnail begin 16x16 12');
  assert.equal(lines[4], '; iVBORw0KGgo=');
  assert.equal(lines[5], '; thumbnail end');
  assert.ok(text.endsWith('G28\nG1 X10\n'));
  assert.ok(text.includes('\n\n; external perimeters'));
  fs.rmSync(dir, { recursive: true, force: true });
});

test('B4: injecting thumbnails never reads the whole G-code into memory', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ws-thumb-b4-'));
  const f = path.join(dir, 'big.gcode');
  // 8 MB of body, far more than a buffer read would be expected to hold for a header rewrite
  const body = 'G1 X1 Y1 E0.1\n'.repeat(500_000);
  fs.writeFileSync(f, '; generated by PrusaSlicer\n' + body);

  // Any full read is a failure: the file is only read in chunks, and the body is streamed into the temp file
  const realReadFileSync = fs.readFileSync;
  const calls: string[] = [];
  fs.readFileSync = ((file: fs.PathOrFileDescriptor, ...rest: unknown[]) => {
    calls.push(String(file));
    return (realReadFileSync as (...a: unknown[]) => unknown)(file, ...rest);
  }) as typeof fs.readFileSync;
  try {
    await injectThumbnails(f, [{ width: 16, height: 16, format: 'PNG', data: 'iVBORw0KGgo=' }]);
  } finally {
    fs.readFileSync = realReadFileSync;
  }
  assert.deepEqual(calls, [], 'injectThumbnails must not call readFileSync');

  const size = fs.statSync(f).size;
  assert.ok(size > body.length, 'the thumbnails were inserted');
  // the thumbnail sits right after the first line and the body is intact
  const head = Buffer.alloc(80);
  const fd = fs.openSync(f, 'r');
  fs.readSync(fd, head, 0, head.length, 0);
  fs.closeSync(fd);
  assert.ok(head.toString('utf8').startsWith('; generated by PrusaSlicer\n'));
  fs.rmSync(dir, { recursive: true, force: true });
});
