/**
 * The `thumbnails` option parser itself is tested in `shared/src/values.test.ts` (R-5 moved it
 * there); this file covers what only the server does with a thumbnail – the G-code block and the
 * rewrite of the file.
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { injectThumbnails, thumbnailBlock } from './thumbnails.js';

test('thumbnail block format', () => {
  const b64 = 'A'.repeat(100);
  const block = thumbnailBlock({ width: 16, height: 16, format: 'QOI', data: b64 });
  const lines = block.trimEnd().split('\n');
  assert.equal(lines[0], ';');
  assert.equal(lines[1], '; thumbnail_QOI begin 16x16 100');
  assert.equal(lines[2].length, 80); // "; " + 78 chars
  assert.equal(lines[3], '; ' + 'A'.repeat(22));
  assert.equal(lines[4], '; thumbnail_QOI end');
  assert.equal(lines[5], ';');
});

test('injectThumbnails rewrites the file after the first line', async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ws-thumb-'));
  const f = path.join(dir, 't.gcode');
  fs.writeFileSync(f, '; generated by PrusaSlicer\n\n; external perimeters extrusion width = 0.45mm\nG28\nG1 X10\n');
  await injectThumbnails(f, [{ width: 16, height: 16, format: 'PNG', data: 'iVBORw0KGgo=' }]);
  const text = fs.readFileSync(f, 'utf8');
  const lines = text.split('\n');
  assert.equal(lines[0], '; generated by PrusaSlicer');
  assert.equal(lines[1], '');
  assert.equal(lines[2], ';');
  assert.equal(lines[3], '; thumbnail begin 16x16 12');
  assert.equal(lines[4], '; iVBORw0KGgo=');
  assert.equal(lines[5], '; thumbnail end');
  assert.ok(text.endsWith('G28\nG1 X10\n'));
  assert.ok(text.includes('\n\n; external perimeters'));
  fs.rmSync(dir, { recursive: true, force: true });
});
