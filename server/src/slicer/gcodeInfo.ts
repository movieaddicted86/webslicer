import fs from 'node:fs';

export interface GcodeInfo {
  generator?: string;
  estimatedTime?: string;
  estimatedTimeSeconds?: number;
  estimatedFirstLayerTime?: string;
  filamentUsedMm?: number[];
  filamentUsedCm3?: number[];
  filamentUsedG?: number[];
  filamentCost?: number[];
  totalFilamentG?: number;
  totalFilamentCost?: number;
  layerHeight?: number;
  firstLayerHeight?: number;
  maxZ?: number;
  layers?: number;
  /** warnings PrusaSlicer printed while the job still produced a G-code */
  warnings?: string[];
  sizeBytes: number;
}

/** A job may warn many times (one block per object); the panel only keeps the first few. */
export const MAX_WARNINGS = 20;

/** `[2026-10-20 14:27:04.825715] [0x00007baeafad6f40] [info]    Slicing process finished…` */
const LOG_PREFIX = /^(?:(?:\[[0-9]{4}-\d\d-\d\d[^\]]*\]|\[0x[0-9a-f]+\]|\[(?:fatal|error|warning|info|debug|trace)\])\s*)+/i;

/** Lines that belong to the slicer's own progress/status output rather than to a warning. */
function isLogNoise(line: string): boolean {
  const t = line.trim();
  return (
    t === '' ||
    LOG_PREFIX.test(t) ||
    /^\d{1,3}\s*=>/.test(t) ||
    /^=>/.test(t) ||
    t.startsWith('$ ') ||
    t.startsWith('WebSlicer:') ||
    t.startsWith('Slicing result exported')
  );
}

/**
 * Warning lines of a slicer run. PrusaSlicer keeps slicing when an object is not printable and
 * prints a block instead:
 *   print warning: Empty layer between 8 and 12.2.
 *   Object name: waist
 *   Make sure the object is printable. …
 * The block's lines after the `warning` line carry the object name and the fix hint, so they are
 * joined into the same entry. Duplicates are dropped, the list is capped at `MAX_WARNINGS`.
 */
export function extractWarnings(lines: string[]): string[] {
  const out: string[] = [];
  for (let i = 0; i < lines.length; i++) {
    if (!/warning/i.test(lines[i])) continue;
    const parts = [lines[i].trim().replace(LOG_PREFIX, '').replace(/^(print\s+)?warning\s*:\s*/i, '')];
    // a following line that warns itself opens the next block instead of continuing this one
    for (let j = i + 1; j < lines.length && parts.length < 3 && !isLogNoise(lines[j]) && !/warning/i.test(lines[j]); j++) {
      parts.push(lines[j].trim());
      i = j;
    }
    const entry = parts.join(' ').replace(/\s+/g, ' ').trim();
    if (entry && !out.includes(entry)) out.push(entry);
    if (out.length >= MAX_WARNINGS) break;
  }
  return out;
}

export function parseDuration(s: string): number {
  let total = 0;
  const re = /(\d+)\s*([dhms])/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(s))) {
    const n = Number(m[1]);
    switch (m[2]) {
      case 'd':
        total += n * 86400;
        break;
      case 'h':
        total += n * 3600;
        break;
      case 'm':
        total += n * 60;
        break;
      case 's':
        total += n;
        break;
    }
  }
  return total;
}

function nums(s: string): number[] {
  return s
    .split(',')
    .map((x) => parseFloat(x.trim()))
    .filter((x) => !Number.isNaN(x));
}

/** Chunk size of the layer scan (the tests use a small one to check chunk boundaries). */
const LAYER_CHUNK = 1 << 20;

/**
 * Number of printed layers. PrusaSlicer writes exactly one `;LAYER_CHANGE` line per layer; the file
 * is scanned in chunks because a G-code can be far too large to read into memory at once.
 */
export function countLayers(file: string, chunkSize = LAYER_CHUNK): number | undefined {
  const size = fs.statSync(file).size;
  const fd = fs.openSync(file, 'r');
  try {
    const buf = Buffer.alloc(Math.max(chunkSize, 1));
    let carry = '';
    let layers = 0;
    let pos = 0;
    while (pos < size) {
      const read = fs.readSync(fd, buf, 0, buf.length, pos);
      if (read <= 0) break;
      pos += read;
      const lines = (carry + buf.toString('utf8', 0, read)).split('\n');
      carry = lines.pop() ?? '';
      for (const line of lines) if (line.replace(/\r$/, '') === ';LAYER_CHANGE') layers++;
    }
    if (carry.replace(/\r$/, '') === ';LAYER_CHANGE') layers++;
    return layers || undefined;
  } catch {
    return undefined;
  } finally {
    fs.closeSync(fd);
  }
}

/** Extract summary information from a PrusaSlicer G-code file (reads head + tail). */
export function readGcodeInfo(file: string): GcodeInfo {
  const stat = fs.statSync(file);
  const info: GcodeInfo = { sizeBytes: stat.size };
  const fd = fs.openSync(file, 'r');
  try {
    const headLen = Math.min(stat.size, 64 * 1024);
    const head = Buffer.alloc(headLen);
    fs.readSync(fd, head, 0, headLen, 0);
    const tailLen = Math.min(stat.size, 128 * 1024);
    const tail = Buffer.alloc(tailLen);
    fs.readSync(fd, tail, 0, tailLen, Math.max(0, stat.size - tailLen));
    const text = head.toString('utf8') + '\n' + tail.toString('utf8');
    for (const line of text.split(/\r?\n/)) {
      if (!line.startsWith(';')) continue;
      let m: RegExpExecArray | null;
      if ((m = /^; generated by (.*)$/.exec(line))) info.generator = m[1].trim();
      else if ((m = /^; estimated printing time \(normal mode\) = (.*)$/.exec(line))) {
        info.estimatedTime = m[1].trim();
        info.estimatedTimeSeconds = parseDuration(m[1]);
      } else if ((m = /^; estimated first layer printing time \(normal mode\) = (.*)$/.exec(line))) info.estimatedFirstLayerTime = m[1].trim();
      else if ((m = /^; filament used \[mm\] = (.*)$/.exec(line))) info.filamentUsedMm = nums(m[1]);
      else if ((m = /^; filament used \[cm3\] = (.*)$/.exec(line))) info.filamentUsedCm3 = nums(m[1]);
      else if ((m = /^; filament used \[g\] = (.*)$/.exec(line))) info.filamentUsedG = nums(m[1]);
      else if ((m = /^; filament cost = (.*)$/.exec(line))) info.filamentCost = nums(m[1]);
      else if ((m = /^; total filament used \[g\] = (.*)$/.exec(line))) info.totalFilamentG = parseFloat(m[1]);
      else if ((m = /^; total filament cost = (.*)$/.exec(line))) info.totalFilamentCost = parseFloat(m[1]);
      else if ((m = /^; layer_height = (.*)$/.exec(line))) info.layerHeight = parseFloat(m[1]);
      else if ((m = /^; first_layer_height = (.*)$/.exec(line))) info.firstLayerHeight = parseFloat(m[1]);
    }
    if (info.totalFilamentG === undefined && info.filamentUsedG) info.totalFilamentG = info.filamentUsedG.reduce((a, b) => a + b, 0);
    info.layers = countLayers(file, LAYER_CHUNK);
  } finally {
    fs.closeSync(fd);
  }
  return info;
}
