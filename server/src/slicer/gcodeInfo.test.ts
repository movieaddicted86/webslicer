import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { countLayers, parseDuration, readGcodeInfo } from './gcodeInfo.js';

function tmpGcode(name: string, content: string): string {
  const file = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'webslicer-gcodeinfo-')), name);
  fs.writeFileSync(file, content);
  return file;
}

const LAYER = ';LAYER_CHANGE\nG1 Z0.4\n;Z:0.4\n';

test('countLayers counts one layer per `;LAYER_CHANGE`, also across chunk boundaries', () => {
  const file = tmpGcode('layers.gcode', `; header\n${LAYER.repeat(7)}; footer\n`);
  assert.equal(countLayers(file), 7);
  // chunk sizes that cut through the lines in the middle
  for (const chunk of [64, 17, 13, 1]) assert.equal(countLayers(file, chunk), 7, `chunk size ${chunk}`);
});

test('countLayers tolerates CRLF and reports no layer count for a file without layers', () => {
  const crlf = tmpGcode('crlf.gcode', ';LAYER_CHANGE\r\n;LAYER_CHANGE\r\n');
  assert.equal(countLayers(crlf, 8), 2);
  assert.equal(countLayers(tmpGcode('plain.gcode', '; no layers here\n')), undefined);
});

test('readGcodeInfo reports time, filament and the layer count', () => {
  const file = tmpGcode(
    'full.gcode',
    [
      '; generated by PrusaSlicer 2.9.6',
      '; estimated printing time (normal mode) = 1h 5m 3s',
      '; filament used [mm] = 3299.35',
      '; filament used [g] = 9.85',
      '; total filament used [g] = 9.85',
      '; total filament cost = 24.99',
      LAYER.repeat(42),
    ].join('\n'),
  );
  const info = readGcodeInfo(file);
  assert.equal(info.generator, 'PrusaSlicer 2.9.6');
  assert.equal(info.estimatedTime, '1h 5m 3s');
  assert.equal(info.estimatedTimeSeconds, 3903);
  assert.equal(info.filamentUsedMm?.[0], 3299.35);
  assert.equal(info.totalFilamentG, 9.85);
  assert.equal(info.totalFilamentCost, 24.99);
  assert.equal(info.layers, 42);
});

test('parseDuration reads days, hours, minutes and seconds', () => {
  assert.equal(parseDuration('17m 35s'), 1055);
  assert.equal(parseDuration('2d 3h 4m 5s'), 2 * 86400 + 3 * 3600 + 4 * 60 + 5);
  assert.equal(parseDuration(''), 0);
});
