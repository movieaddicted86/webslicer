/**
 * Milestone A: the app loads, imports a model, slices it and shows the preview.
 *
 * This is the spec the CI job runs first: it proves the whole chain (static frontend → REST → the
 * PrusaSlicer CLI → G-code preview) works against the fixture data, so a failure in the area specs
 * below is about the area and not about the stack.
 */
import { CUBE, importFile, read, sliceAndWait, state } from '../helpers/app';
import { expect, test } from '../helpers/fixtures';
import { E2E_PRINTER } from '../global-setup';
import { frameProbe } from '../helpers/canvas';

test.describe('smoke: the app slice chain', () => {
  test('the fixture printer is selected and the plater is empty', async ({ app }) => {
    const s = await state(app);
    expect(s.fatal).toBeUndefined();
    expect(s.presets.printer.name).toBe(E2E_PRINTER);
    // the fixture printer has one extruder, so the single-material controls are the ones shown
    expect(s.extruderCount()).toBe(1);
    // the MK3S bed: 250 × 210 mm
    expect(s.presets.printer.current.bed_shape).toBe('0x0,250x0,250x210,0x210');
    expect(s.objects).toHaveLength(0);
  });

  test('importing a model uploads it and places it centred on the bed', async ({ app }) => {
    await importFile(app, CUBE);
    const s = await state(app);
    expect(s.objects).toHaveLength(1);
    expect(s.objects[0].modelId).toBeTruthy();
    expect(s.objects[0].triangles).toBeGreaterThan(0);

    const frame = await frameProbe(app);
    expect(frame.objects).not.toBeNull();
    const box = frame.objects as [number, number, number, number];
    expect(Math.abs((box[0] + box[2]) / 2)).toBeLessThan(0.25);
    expect(Math.abs((box[1] + box[3]) / 2)).toBeLessThan(0.25);
  });

  test('the slice finishes and the preview has layers', async ({ app }) => {
    await importFile(app, CUBE);
    await sliceAndWait(app);
    const s = await state(app);
    expect(s.job?.status).toBe('done');
    expect(s.gcode).toBeTruthy();
    expect(s.gcode?.layerCount).toBeGreaterThan(0);
    expect(s.gcode?.segmentCount).toBeGreaterThan(0);

    const layers = await read(app, (st) => st.gcode?.layerCount ?? 0);
    expect(layers).toBeGreaterThan(0);
  });

  test('the slice panel reports the job and the export link points at its G-code', async ({ app }) => {
    await importFile(app, CUBE);
    await sliceAndWait(app);
    await app.evaluate(() => window.webslicer.getState().setView('preview'));
    await app.waitForTimeout(1500);

    const jobId = await read(app, (s) => s.job?.id);
    const href = await app.locator('.stats a.button.primary').first().getAttribute('href');
    expect(href).toBe(`/api/jobs/${jobId}/gcode?download`);

    // the file the link serves really is G-code with the preview's layers
    const head = await app.evaluate(async (id) => {
      const res = await fetch(`/api/jobs/${id}/gcode`, { headers: { range: 'bytes=0-2000' } });
      return (await res.text()).slice(0, 200);
    }, jobId);
    expect(head).toContain('generated by PrusaSlicer');
  });
});
